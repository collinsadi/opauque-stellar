/**
 * Prove the frontend typecheck gate actually fails (#1088).
 *
 * main once merged code that `tsc -b` rejects because the CI step ran an unrelated
 * `tsc` npm package from the repo root instead of the project's TypeScript. This
 * script injects one instance of every error class that slipped through into a
 * temporary source file, runs the same `tsc -b` as `npm run typecheck`, and fails
 * unless the compiler exits non-zero and reports each expected diagnostic.
 *
 *   npm run typecheck:gate
 */
import { spawnSync } from "node:child_process";
import { rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const FRONTEND = join(dirname(fileURLToPath(import.meta.url)), "..");
const CANARY_NAME = "__typecheck_gate_canary__.ts";
const CANARY = join(FRONTEND, "src", CANARY_NAME);

/** Each error class from #1087/#1088, with the diagnostic tsc must report. */
const CASES: Array<{ code: string; what: string; source: string }> = [
  {
    code: "TS2307",
    what: "import of a package that is not installed (lucide-react)",
    source: 'import { NotInstalled } from "typecheck-gate-missing-package";\nexport const usesMissing = NotInstalled;',
  },
  {
    code: "TS2304",
    what: "reference to an undeclared variable (ModalShell `busy`)",
    source: "export const usesUndeclared = undeclaredBusyFlag;",
  },
  {
    code: "TS6133",
    what: "unused local under noUnusedLocals (STROOP_FEE_BUFFER, decodedPaymentLink)",
    source: "function gateUnused() {\n  const STROOP_FEE_BUFFER = 1n;\n}\nexport { gateUnused };",
  },
  {
    code: "TS2339",
    what: 'import.meta.vitest under types: ["vite/client"] (pollingUtils)',
    source: "export const inSourceTests = import.meta.vitest;",
  },
];

function run(): number {
  writeFileSync(CANARY, `// Generated by scripts/verify-typecheck-gate.ts — safe to delete.\n${CASES.map((c) => c.source).join("\n")}\n`);
  try {
    const res = spawnSync("npx", ["tsc", "-b", "--pretty", "false"], { cwd: FRONTEND, encoding: "utf8" });
    const output = `${res.stdout ?? ""}${res.stderr ?? ""}`;
    const canaryLines = output.split("\n").filter((line) => line.includes(CANARY_NAME));
    let failed = false;
    if (res.status === 0) {
      console.error("FAIL: tsc -b exited 0 even though the canary file has type errors.");
      failed = true;
    }
    for (const c of CASES) {
      const hit = canaryLines.some((line) => line.includes(`error ${c.code}:`));
      console.log(`${hit ? "ok  " : "FAIL"} ${c.code} ${c.what}`);
      if (!hit) failed = true;
    }
    const unrelated = output.split("\n").filter((line) => /error TS\d+/.test(line) && !line.includes(CANARY_NAME));
    if (unrelated.length > 0) {
      console.error("FAIL: the tree has type errors outside the canary:\n" + unrelated.join("\n"));
      failed = true;
    }
    if (failed) {
      console.error(output);
      return 1;
    }
    console.log(`Typecheck gate rejects all ${CASES.length} error classes (tsc exit ${res.status}).`);
    return 0;
  } finally {
    rmSync(CANARY, { force: true });
  }
}

for (const signal of ["SIGINT", "SIGTERM"] as const) {
  process.on(signal, () => {
    rmSync(CANARY, { force: true });
    process.exit(130);
  });
}

process.exit(run());
